function syncPackageFiles() {
  for (const [packageName, config] of Object.entries(packageConfigs)) {
    const packageDir = path.join(root, 'packages', config.dir)
    const packageJsonPath = path.join(packageDir, 'package.json')
    const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8'))
    const files = Array.isArray(packageJson.files) ? packageJson.files : ['dist', 'README.md']
    packageJson.files = normalizePackageFiles(files)
    writeAbsolute(packageJsonPath, `${JSON.stringify(packageJson, null, 2)}\n`)

    const oldSkill = path.join(packageDir, 'SKILL.md')
    if (existsSync(oldSkill)) {
      rmSync(oldSkill)
    }

    writePackageAi(packageName, config)
    writePackageReadme(packageName, config)
  }
}

function normalizePackageFiles(files) {
  const next = []
  for (const file of files) {
    if (file !== 'SKILL.md' && !next.includes(file)) next.push(file)
  }
  if (!next.includes('README.md')) next.push('README.md')
  if (!next.includes('AI.md')) {
    const readmeIndex = next.indexOf('README.md')
    next.splice(readmeIndex + 1, 0, 'AI.md')
  }
  return next
}

