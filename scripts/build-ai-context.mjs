function validateAiSource() {
  for (const rel of ['index.md', 'package-map.md', 'conventions.md', 'anti-patterns.md']) {
    assertExists(path.join(aiDir, rel))
  }

  for (const rel of markdownFiles(path.join(aiDir, 'packages'))) {
    const text = ai(rel)
    const missing = requiredPackageSections.filter((heading) => !text.includes(heading))
    if (missing.length) {
      throw new Error(`${rel} is missing required sections: ${missing.join(', ')}`)
    }
  }

  for (const [name, config] of Object.entries(packageConfigs)) {
    assertExists(path.join(root, 'packages', config.dir, 'package.json'))
    const extraSectionFiles = (config.extraSections ?? []).map((extra) => extra.rel)
    for (const rel of [...config.cards, ...config.recipes, ...extraSectionFiles]) {
      assertExists(path.join(aiDir, rel), `${name} references missing AI source ${rel}`)
    }
  }
}

